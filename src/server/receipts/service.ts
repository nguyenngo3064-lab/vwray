/**
 * Simulated receipts.
 *
 * A receipt is a permanent record of a calculation, so it must be reproducible:
 *   * every money value comes from the ONE arithmetic routine in billing/service.ts,
 *     never from a second formula,
 *   * the exact bytes and pricing are stored on the row,
 *   * a canonical payload is hashed with SHA-256 and the hash is stored, so
 *     /receipts/verify/{number} can prove the document was not altered.
 *
 * What a receipt is NOT: an official payment document. The disclaimer is mandatory,
 * the optional stamp is clearly a simulation stamp, and no provider authorisation,
 * transaction id or seal is ever fabricated. When an operator sets the provider label
 * to a third-party name, the disclaimer states explicitly that this document was not
 * issued by that provider.
 */

export const SIMULATION_STAMP_DEFAULT = "SIMULATION - NOT AN OFFICIAL PAYMENT DOCUMENT";

const BASE_DISCLAIMER =
  "This is a simulated receipt generated by the VWRAY control plane. It is not an official payment " +
  "document, it is not issued by any telecommunications provider, and it is not proof of payment. " +
  "No payment processor is connected to this installation.";

/** Exact wording the brief requires when the Wicore label is used. */
export const WICORE_DISCLAIMER =
  "Biên lai mô phỏng – không phải chứng từ thanh toán chính thức của Wicore.";

export function disclaimerFor(providerLabel: string): string {
  const isWicore = providerLabel.trim().toLowerCase().includes("wicore");
  return isWicore ? `${BASE_DISCLAIMER} ${WICORE_DISCLAIMER}` : BASE_DISCLAIMER;
}

export interface ReceiptCalculation {
  rawGb: number;
  optimizedGb: number;
  savedGb: number;
  freeQuotaGb: number;
  billableGb: number;
  baseFee: number;
  pricePerGb: number;
  subtotal: number;
  total: number;
  currency: string;
  formula: string;
}

export function calculationFrom(breakdown: CostBreakdown): ReceiptCalculation {
  const optimizedGb = Number(breakdown.optimizedBytes) / 1024 ** 3;
  return {
    rawGb: Math.round(breakdown.rawGb * 1000) / 1000,
    optimizedGb: Math.round(optimizedGb * 1000) / 1000,
    savedGb: Math.round((Number(breakdown.savedBytes) / 1024 ** 3) * 1000) / 1000,
    freeQuotaGb: breakdown.freeQuotaGb,
    billableGb: breakdown.billableGb,
    baseFee: breakdown.baseFee,
    pricePerGb: breakdown.pricePerGb,
    subtotal: Math.round(breakdown.billableGb * breakdown.pricePerGb * 100) / 100,
    total: breakdown.computedCost,
    currency: breakdown.currency,
    formula: breakdown.formula,
  };
}

